'use strict';

const fs = require('fs');
const path = require('path');
const assert = require('assert');

const { buildWrappedLabelFixture } = require('./fixtures/build-wrapped-label-pdf');
const {
  extractPositionedText, groupIntoRows, mergeWrappedLabelRows,
  detectColumnAnchors, extractRows,
} = require('../src/core/pdf-coordinates');

let pass = 0, fail = 0;
const failures = [];
function test(name, fn) {
  return fn().then(() => { pass++; console.log(`  PASS  ${name}`); })
    .catch((e) => { fail++; failures.push({ name, message: e.message }); console.log(`  FAIL  ${name}\n        ${e.message}`); });
}

const COLUMN_DEFS = [
  { key: 'PREMIUM_95', patterns: [/^M95$/] },
  { key: 'REGULAR_91', patterns: [/^M91$/] },
  { key: 'DIESEL', patterns: [/^ADF$/] },
];

async function main() {
  console.log('\nPDF COORDINATE EXTRACTION — real pdfjs-dist against a real synthetic PDF');
  console.log('(fixture generated by pdf-lib; see fixtures/build-wrapped-label-pdf.js for why)\n');

  const fixturePath = path.join(__dirname, 'fixtures', 'wrapped-label-fixture.pdf');
  if (!fs.existsSync(fixturePath)) {
    const bytes = await buildWrappedLabelFixture();
    fs.writeFileSync(fixturePath, bytes);
  }
  const pdfBytes = fs.readFileSync(fixturePath);

  await test('this is a real PDF file (starts with %PDF-)', async () => {
    assert.strictEqual(pdfBytes.slice(0, 5).toString('ascii'), '%PDF-');
  });

  const pages = await extractPositionedText(pdfBytes);

  await test('extractPositionedText reads real positioned text items from real PDF bytes', async () => {
    assert.strictEqual(pages.length, 1);
    assert.ok(pages[0].items.length > 15, `expected >15 items, got ${pages[0].items.length}`);
  });

  await test('items carry real x/y coordinates (not left-to-right token order)', async () => {
    const wiri = pages[0].items.find((i) => i.str === 'Wiri');
    assert.ok(wiri && typeof wiri.x === 'number' && typeof wiri.y === 'number');
  });

  const rowsRaw = groupIntoRows(pages[0].items);

  await test('groupIntoRows finds 7 visual rows before wrap-merging (header + 6 data lines)', async () => {
    assert.strictEqual(rowsRaw.length, 7, `got ${rowsRaw.length}`);
  });

  const merged = mergeWrappedLabelRows(rowsRaw.slice(1)); // drop header row first

  await test('mergeWrappedLabelRows collapses the two wrapped Mount/Maunganui pairs (6 lines -> 4 rows)', async () => {
    assert.strictEqual(merged.length, 4, `got ${merged.length} rows: ${JSON.stringify(merged.map(r => r.items.map(i => i.str)))}`);
  });

  const anchors = detectColumnAnchors(rowsRaw[0].items, COLUMN_DEFS);

  await test('detectColumnAnchors reads column x-positions from the header row itself', async () => {
    assert.strictEqual(anchors.length, 3);
    assert.strictEqual(anchors.find((a) => a.key === 'DIESEL').label, 'ADF');
  });

  const dataItems = pages[0].items.filter((it) => !rowsRaw[0].items.includes(it));
  const rows = extractRows(dataItems, anchors);

  await test('4 logical rows extracted from 6 physical text lines', async () => {
    assert.strictEqual(rows.length, 4, JSON.stringify(rows.map((r) => r.label)));
  });

  await test('CRITICAL: "Mount" + "Maunganui" wrapped across two lines merges into one label', async () => {
    const r = rows.find((r) => r.label === 'NZOSL Mount Maunganui');
    assert.ok(r, `not found among: ${rows.map((r) => r.label).join(' | ')}`);
  });

  await test('CRITICAL: second wrapped Mount Maunganui (different operator) is a SEPARATE row, not merged into the first', async () => {
    const r = rows.find((r) => r.label === 'TNZ Mount Maunganui');
    assert.ok(r);
  });

  await test('sparse wrapped row 1 (NZOSL): only ADF assigned, correct value, no cross-column guess', async () => {
    const r = rows.find((r) => r.label === 'NZOSL Mount Maunganui');
    assert.deepStrictEqual(r.values, { DIESEL: 250.66 });
    assert.strictEqual(r.unassigned.length, 0);
  });

  await test('sparse wrapped row 2 (TNZ): only M91 assigned, correct value', async () => {
    const r = rows.find((r) => r.label === 'TNZ Mount Maunganui');
    assert.deepStrictEqual(r.values, { REGULAR_91: 282.85 });
  });

  await test('fully-populated non-wrapped row (Wiri) still extracts all 3 columns correctly', async () => {
    const r = rows.find((r) => r.label === 'WOSL Wiri');
    assert.deepStrictEqual(r.values, { PREMIUM_95: 296.38, REGULAR_91: 282.58, DIESEL: 250.25 });
  });

  await test('a normal row near the wrapped block (Dunedin) is not accidentally merged into anything', async () => {
    const r = rows.find((r) => r.label === 'NZOSL Dunedin');
    assert.ok(r);
    assert.deepStrictEqual(r.values, { PREMIUM_95: 300.45, REGULAR_91: 286.19, DIESEL: 250.66 });
  });

  await test('values assigned to columns by x-coordinate, not left-to-right position (this is the core safety property)', async () => {
    // If this were positional (token order) instead of coordinate-based,
    // TNZ Mount Maunganui's single value (282.85, physically under the M91
    // header) would risk landing in whatever column comes "first" -- it must
    // land specifically in REGULAR_91 because that's where its x-position is.
    const r = rows.find((r) => r.label === 'TNZ Mount Maunganui');
    assert.strictEqual(r.values.REGULAR_91, 282.85);
    assert.strictEqual(r.values.PREMIUM_95, undefined);
    assert.strictEqual(r.values.DIESEL, undefined);
  });

  console.log(`\n${'='.repeat(70)}\n  PDF COORDINATE EXTRACTION: ${pass} passed, ${fail} failed\n${'='.repeat(70)}`);
  console.log('\nNOTE: tested against a real, generated PDF file reproducing BP\'s known');
  console.log('wrapped-line/sparse-column layout. Running this module against the LIVE');
  console.log('BP PDF bytes is LIVE VERIFICATION REQUIRED — this sandbox\'s network');
  console.log('egress does not reach bp.com, so those bytes were not obtainable here.');

  if (fail) { failures.forEach((f) => console.log(` - ${f.name}: ${f.message}`)); process.exitCode = 1; }
}

main();
