  function buildDocuments(currentPrices) {
    const seen = new Set();
    const docs = [];
    currentPrices.forEach((r) => {
      const k = r.sourceDocumentUrl + r.effectiveDate;
      if (seen.has(k)) return;
      seen.add(k);
      docs.push({
        supplierId: r.supplierId, supplierName: r.supplierName,
        documentUrl: r.sourceDocumentUrl, effectiveDate: r.effectiveDate,
        retrievedAt: r.retrievedAt,
        hash: hashSeed(k).toString(16).padStart(8, '0') + hashSeed(k + 'x').toString(16).padStart(8, '0'),
        productsFound: [...new Set(currentPrices.filter((x) => x.sourceDocumentUrl === r.sourceDocumentUrl && x.effectiveDate === r.effectiveDate).map((x) => x.productShort))],
        terminalsFound: [...new Set(currentPrices.filter((x) => x.sourceDocumentUrl === r.sourceDocumentUrl && x.effectiveDate === r.effectiveDate).map((x) => x.terminalName))],
        status: 'PROCESSED',
      });
    });
    return docs.sort((a, b) => b.effectiveDate.localeCompare(a.effectiveDate));
  }

