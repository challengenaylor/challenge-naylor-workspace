  // ---------------------------------------------------------------- history
  // Weekly series per (supplier, region, product) that AVAILABILITY permits.
  // Anchored at the two real observations, then walked backward synthetically.
  function buildHistory(currentPrices, weeksBack) {
    const out = [];
    const grouped = {};
    currentPrices.forEach((r) => {
      const key = [r.supplierId, r.regionId, r.terminalName, r.productId].join('::');
      (grouped[key] = grouped[key] || []).push(r);
    });

    Object.entries(grouped).forEach(([key, recs]) => {
      const r = recs[0];
      const rng = mulberry32(hashSeed(key));
      const points = [];

      // Real anchor points first.
      points.push({ date: r.effectiveDate, value: r.currentValue });
      let anchorValue = r.currentValue;
      let anchorDate = r.effectiveDate;
      if (typeof r.previousValue === 'number') {
        points.push({ date: r.previousEffectiveDate, value: r.previousValue });
        anchorValue = r.previousValue;
        anchorDate = r.previousEffectiveDate;
      }

      // Walk backward synthetically, one point per week.
      let value = anchorValue;
      let date = new Date(anchorDate + 'T00:00:00Z');
      for (let i = points.length; i < weeksBack; i++) {
        date = new Date(date.getTime() - 7 * 86400000);
        const drift = (rng() - 0.52) * 0.02;      // slight long-run downward drift
        const noise = (rng() - 0.5) * 0.03;        // weekly volatility ~1.5% each way
        value = Math.max(150, Math.min(340, value * (1 - drift - noise)));
        points.push({ date: date.toISOString().slice(0, 10), value: +value.toFixed(2) });
      }

      points.forEach((p) => out.push({
        supplierId: r.supplierId, supplierName: r.supplierName, supplierColor: r.supplierColor,
        regionId: r.regionId, regionLabel: r.regionLabel, terminalName: r.terminalName,
        productId: r.productId, productName: r.productName,
        effectiveDate: p.date, value: p.value,
      }));
    });

    return out.sort((a, b) => a.effectiveDate.localeCompare(b.effectiveDate));
  }

  // ---------------------------------------------------------------- AIP
  // Synthetic weekday-only AIP series (AUD cents/litre), two grades. Trend is
  // deliberately downward over the final fortnight so the Market Direction
  // demo has a real, explicable non-neutral state to show — see calculations.js.
  function buildAip(days) {
    const rng = mulberry32(hashSeed('AIP-ULP-DIESEL-2026'));
    const out = [];
    let ulp = 168.4, diesel = 172.1;
    let date = new Date();
    const series = [];
    while (series.length < days) {
      const dow = date.getUTCDay();
      if (dow !== 0 && dow !== 6) series.push(new Date(date));
      date = new Date(date.getTime() - 86400000);
    }
    series.reverse();
    series.forEach((d, i) => {
      const fromEnd = series.length - i;
      const trend = fromEnd <= 12 ? 0.0035 : -0.0006; // downward push in the most recent ~12 weekdays
      ulp = Math.max(120, ulp * (1 - trend - (rng() - 0.5) * 0.01));
      diesel = Math.max(120, diesel * (1 - trend - (rng() - 0.5) * 0.009));
      out.push({
        date: d.toISOString().slice(0, 10),
        ulp: +ulp.toFixed(2),
        diesel: +diesel.toFixed(2),
        unit: 'AU_CENTS_PER_LITRE',
        source: 'https://www.aip.com.au/pricing/terminal-gate-prices',
      });
    });
    return out;
  }

